        "    rtf = elapsed / audio_seconds if audio_seconds > 0 else 0.0",
        '    refs = [normalize_arabic(it["reference_raw"], norm_cfg) for it in items]',
        "    hyps = [normalize_arabic(h, norm_cfg) for h in hyps_raw]",
        "    scored = score_utterances(refs, hyps)",
